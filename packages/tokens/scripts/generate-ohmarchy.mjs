/* Generates src/ohmarchy.css and src/ohmarchy.json from omarchy/mapping.js over the two
   static-default fixtures. The law is omarchy/mapping.js.

   The output is DETERMINISTIC and committed: test/ohmarchy-regeneration.test.ts re-runs
   this generation in-process and fails if the committed files differ, so a hand edit of
   either output cannot survive a test run. Never hand-pick a value — change mapping.js
   and regenerate.

   Selector contract (the appearance attributes):
     data-face   "ohmarchy" | absent (= paper)   — this file only styles the present state
     data-theme  "light" | "dark" | absent (= system, via prefers-color-scheme)
   The media-scoped dark rule repeats tokens.css's `:root:not(...):not(...)` arity so its
   specificity (0,3,0) ties paper's system-dark block and wins by order — ohmarchy.css is
   imported after tokens.css (packages/ui/src/index.ts). */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (rel) => fileURLToPath(new URL(rel, import.meta.url));

await import(here("../omarchy/mapping.js")); // UMD: registers globalThis.OHMARCHY_MAP under ESM
const MAP = globalThis.OHMARCHY_MAP;

const DARK_FIXTURE = "tokyo-night"; // Omarchy's install default, verified on the 4.0.2 VM
const LIGHT_FIXTURE = "flexoki-light"; // no designated light default exists; OHMARCHY-TOKENS.md §4

const load = (slug) => JSON.parse(readFileSync(here(`../omarchy/fixtures/${slug}.json`), "utf8"));
const dark = MAP.mapTheme(load(DARK_FIXTURE));
const light = MAP.mapTheme(load(LIGHT_FIXTURE));

/* The teaching-intensity switch — OHMARCHY-CONTRACT.md's `--teach`, defined ONLY in the token
   stylesheet's face blocks (paper's 0 lives in faces.css). NOT part of mapping.js: it is the
   contract's own constant per face, not a palette derivation, so it joins here — the CSS gains
   it, src/ohmarchy.json stays the mapping's pure output (the spec-identity pin). */
const teachCss = (tokens) => ({ ...tokens, "--teach": "1" });

/** One CSS rule body from a mapTheme token record, two-space indented. */
function body(tokens, indent) {
  return Object.entries(tokens)
    .map(([k, v]) => `${indent}${k}: ${v};`)
    .join("\n");
}

const banner = `/* =====================================================================
   @ohmail/tokens — the ohmarchy face (OHMARCHY-PLAN.md §3a).
   GENERATED by scripts/generate-ohmarchy.mjs from omarchy/mapping.js over
   the ${DARK_FIXTURE} (dark) and ${LIGHT_FIXTURE} (light) fixtures — never
   hand-edited (test/ohmarchy-regeneration.test.ts enforces it; identity to
   the spec's ohmarchy.tokens.json is held by ohmarchy-spec-identity).

   Paper is the ABSENT state of data-face: nothing in this file matches a
   document without data-face="ohmarchy", which is what keeps the paper
   face byte-identical by construction (test/faces-paper-purity.test.ts).
   --z-*, --split and the layout slots are deliberately not overridden:
   layer order and column math are not appearance (OHMARCHY-TOKENS.md §1).
   ===================================================================== */
`;

const css = `${banner}
[data-face="ohmarchy"],
[data-face="ohmarchy"][data-theme="light"]{
${body(teachCss(light.tokens), "  ")}
}
/* nested scheme scopes — a SUBTREE forced light/dark inside an ohmarchy page (the dark
   viewer's per-message light rendering, showcase panels) must resolve the ohmarchy scheme
   set, not tokens.css's paper one: face and theme are required on one element by the blocks
   above, so the descendant forms here keep scheme orthogonal to face (review-caught;
   OHMARCHY-CONTRACT.md: data-theme keeps meaning "scheme, in either face"). */
[data-face="ohmarchy"] [data-theme="light"]{
${body(teachCss(light.tokens), "  ")}
}
[data-face="ohmarchy"][data-theme="dark"],
[data-face="ohmarchy"] [data-theme="dark"]{
${body(teachCss(dark.tokens), "  ")}
}
/* system preference — applies only while no explicit theme is set; the
   selector's :not() arity ties tokens.css's system-dark rule so import
   order (this file second) decides, exactly as the base rules above tie
   tokens.css's :root. */
@media (prefers-color-scheme: dark){
  [data-face="ohmarchy"]:not([data-theme="light"]):not([data-theme="dark"]){
${body(teachCss(dark.tokens), "    ")}
  }
}
`;

const json = {
  _provenance: {
    rule:
      "GENERATED by scripts/generate-ohmarchy.mjs from omarchy/mapping.js — never hand-edited. " +
      "The spec statement of the same output is the design prototypes' ohmarchy.tokens.json, held equal " +
      "by test/ohmarchy-spec-identity.test.ts.",
    dark_source: DARK_FIXTURE,
    light_source: LIGHT_FIXTURE,
  },
  "ohmarchy-dark": dark.tokens,
  "ohmarchy-light": light.tokens,
};

writeFileSync(here("../src/ohmarchy.css"), css);
writeFileSync(here("../src/ohmarchy.json"), JSON.stringify(json, null, 2) + "\n");
console.log(
  `ohmarchy.css + ohmarchy.json written: ${Object.keys(dark.tokens).length} dark / ` +
    `${Object.keys(light.tokens).length} light declarations (${DARK_FIXTURE} / ${LIGHT_FIXTURE})`,
);
